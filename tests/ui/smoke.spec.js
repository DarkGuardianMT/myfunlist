import { test, expect, bookTitle, checkLayout, capture } from './fixtures.js'

test('anonymous navigation, responsive controls and theme switching', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Track what you love.' })).toBeVisible()
  await page.getByRole('link', { name: 'Discover media' }).click()
  await expect(page.getByRole('heading', { name: 'Discover books' })).toBeVisible()
  const mobile = testInfo.project.name === 'mobile'
  const navigation = page.getByRole('navigation', { name: mobile ? 'Mobile navigation' : 'Main navigation', exact: true })
  await expect(navigation).toBeVisible()
  if (mobile) await expect(navigation.getByRole('link')).toHaveCount(5)
  await page.getByRole('button', { name: 'Movies', exact: true }).click()
  await expect(page.getByLabel('Movie title', { exact: true })).toBeVisible()
  await navigation.getByRole('link', { name: 'Login', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Login', exact: true })).toBeVisible()
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).filter({ visible: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await checkLayout(page)
})

test('mocked book discovery, disclosure, filters, detail and return navigation', async ({ page, sandbox }, testInfo) => {
  await page.goto('/discover?provider=google-books')
  await page.getByRole('searchbox', { name: 'Title, author, or ISBN', exact: true }).fill('lantern-fixture')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: bookTitle }) })
  await expect(card).toBeVisible()
  await expect(card.getByRole('img', { name: `Cover of ${bookTitle}` })).toBeVisible()
  await card.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(card.getByRole('region', { name: `Full title and authors for ${bookTitle}` })).toBeVisible()
  await page.getByLabel('Language', { exact: true }).selectOption('nl')
  await expect(page.getByText(/Requested Dutch from Google Books/)).toBeVisible()
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('nl')
  await checkLayout(page)
  await capture(page, testInfo, 'discover-light', card)
  await card.getByRole('link', { name: bookTitle, exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: bookTitle })).toBeVisible()
  await expect(page.getByText('Example Press', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to dark mode', exact: true }).filter({ visible: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await checkLayout(page)
  await capture(page, testInfo, 'detail-dark')
  await page.locator('.media-detail-back').click()
  await expect(page.getByRole('heading', { name: 'Discover books' })).toBeVisible()
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('nl')
  await expect(card).toBeVisible()
  expect(sandbox.googleRequests).toBe(2)
})

test('empty results, controlled network failure, manual retry and disabled Open Library', async ({ page, sandbox }) => {
  await page.goto('/discover?provider=google-books')
  const query = page.getByRole('searchbox', { name: 'Title, author, or ISBN', exact: true })
  await query.fill('empty-fixture')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByText(/No books found for/)).toBeVisible()
  sandbox.offline = true
  await query.fill('offline-fixture')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'We could not reach Google Books' })).toBeVisible()
  expect(sandbox.expectedFailures).toBe(1)
  sandbox.offline = false
  await page.getByRole('button', { name: 'Retry search', exact: true }).click()
  await expect(page.getByRole('heading', { name: bookTitle })).toBeVisible()
  await page.getByLabel('Book catalogue', { exact: true }).selectOption('open-library')
  await expect(page.getByText(/Open Library discovery is awaiting operational and policy checks/)).toBeVisible()
  await expect(page.locator('#open-library-query')).toBeDisabled()
  expect(sandbox.pilotRequests).toBe(0)
  await checkLayout(page)
})
