import { test, expect, checkLayout, capture } from './fixtures.js'
import { fullApp } from './fullAppFixture.js'

const navigation = (page, info) => page.getByRole('navigation', { name: info.project.name === 'mobile' ? 'Mobile navigation' : 'Main navigation', exact: true })

test('Discover navigation: Movies default, explicit Books, legacy URLs and provider gates', async ({ page, sandbox }, info) => {
  fullApp(sandbox)
  await page.goto('/')
  await expect(page.getByRole('group', { name: 'Search media type' }).getByRole('button', { name: 'Movies', exact: true })).toHaveAttribute('aria-pressed', 'true')
  for (const type of ['movie', 'tv', 'game', 'book']) await expect(page.locator(`.home-world[data-type="${type}"]`)).toHaveAttribute('href', `/discover?type=${type}`)
  await page.getByLabel('Search by title', { exact: true }).fill('lantern')
  await page.getByRole('button', { name: 'Find media', exact: true }).click()
  await expect(page).toHaveURL(/type=movie&q=lantern/)
  await expect(page.locator('.discovery-search article')).toHaveCount(6)
  await navigation(page, info).getByRole('link', { name: 'Discover', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Discover movies', exact: true })).toBeVisible()
  await expect(page.locator('.discovery-search article')).toHaveCount(0)
  await page.getByRole('button', { name: 'Books', exact: true }).click()
  await expect(page).toHaveURL(/type=book/)
  await expect(page.getByLabel('Book catalogue')).toHaveValue('google-books')
  await page.locator('#book-query').fill('lantern')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.locator('.discovery-search article')).toHaveCount(6)
  await expect(page).toHaveURL(/type=book/)
  await page.getByLabel('Book catalogue').selectOption('open-library')
  await expect(page).toHaveURL(/type=book&provider=open-library/)
  await expect(page.locator('#open-library-query')).toBeDisabled()
  expect(sandbox.pilotRequests).toBe(0)
  await page.getByLabel('Book catalogue').selectOption('google-books')
  await expect(page).toHaveURL(/type=book&provider=google-books/)
  await page.goto('/discover?q=legacy-book&field=title&lang=nl')
  await expect(page.locator('.discovery-search article')).toHaveCount(6)
  await expect(page).toHaveURL(/type=book/)
  await expect(page.getByLabel('Search in', { exact: true })).toHaveValue('title')
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('nl')
  await checkLayout(page)
  await capture(page, info, 'discover-navigation-books', page.locator('.book-search-panel'))
})

test('Discover navigation: failed RAWG, empty and pending states survive returns without retries', async ({ page, sandbox }, info) => {
  const { records } = fullApp(sandbox)
  await page.clock.install()
  let requests = 0
  let mode = 'error'
  let finish
  sandbox.apiResponses['GET /api/v1/discover/game'] = async () => {
    requests++
    if (mode === 'error') return { status: 503, json: { error: { code: 'provider_unavailable', message: 'Synthetic unavailable.' } } }
    if (mode === 'pending') await new Promise(resolve => { finish = resolve })
    return { json: { data: mode === 'empty' ? [] : records.game } }
  }
  await page.goto('/discover?type=game&q=offline-fixture')
  const failure = page.getByRole('alert').filter({ hasText: 'RAWG is temporarily unavailable' })
  await expect(failure).toBeVisible()
  await navigation(page, info).getByRole('link', { name: 'Library', exact: true }).click()
  await expect(page.locator('.library-grid > article')).toHaveCount(12)
  await page.clock.fastForward(6 * 60 * 1000)
  await page.goBack()
  await expect(failure).toBeVisible()
  expect(requests).toBe(1)
  const retry = page.getByRole('button', { name: 'Retry search', exact: true })
  await retry.evaluate(element => element.scrollIntoView({ block: 'center', behavior: 'instant' }))
  await capture(page, info, 'discover-navigation-rawg-error', retry)
  mode = 'empty'
  await page.getByRole('button', { name: 'Retry search', exact: true }).click()
  await expect(page.getByText(/No games found for/)).toBeVisible()
  expect(requests).toBe(2)
  await navigation(page, info).getByRole('link', { name: 'Library', exact: true }).click()
  await page.goBack()
  await expect(page.getByText(/No games found for/)).toBeVisible()
  expect(requests).toBe(2)
  mode = 'pending'
  await page.locator('#game-query').fill('new-pending-fixture')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.locator('.catalogue-skeletons')).toBeVisible()
  await expect.poll(() => typeof finish).toBe('function')
  await navigation(page, info).getByRole('link', { name: 'Library', exact: true }).click()
  await page.goBack()
  await expect(page.locator('.catalogue-skeletons')).toBeVisible()
  expect(requests).toBe(3)
  mode = 'success'
  finish()
  await expect(page.locator('.discovery-search article')).toHaveCount(6)
  await page.clock.fastForward(6 * 60 * 1000)
  await page.locator('.discovery-search article h3 a').first().click()
  await expect(page.locator('.media-detail-back')).toContainText('Back to Discover')
  await page.locator('.media-detail-back').press('Enter')
  await expect(page.locator('.discovery-search article')).toHaveCount(6)
  expect(requests).toBe(3)
  await checkLayout(page)
})

test('Discover navigation: context Back preserves Discover, Library and specific List and refresh is safe', async ({ page, sandbox }, info) => {
  fullApp(sandbox)
  await page.goto('/discover?type=movie&q=lantern&resultYear=2025')
  await expect(page.locator('.discovery-search article')).toHaveCount(6)
  const discover = page.url()
  await page.locator('.discovery-search article h3 a').first().click()
  await expect(page.locator('.media-detail-back')).toContainText('Back to Discover')
  await capture(page, info, 'discover-navigation-back-discover')
  await page.locator('.media-detail-back').press('Enter')
  await expect(page).toHaveURL(discover)
  await expect(page.locator('#movie-result-year')).toHaveValue('2025')
  await navigation(page, info).getByRole('link', { name: 'Library', exact: true }).click()
  await expect(page.locator('.library-grid > article')).toHaveCount(12)
  await page.getByRole('button', { name: 'Compact', exact: true }).click()
  await page.getByLabel('Sort by', { exact: true }).selectOption('title')
  await page.evaluate(() => window.scrollTo(0, 180))
  const libraryLink = page.locator('.library-grid > article h3 a').first()
  await libraryLink.scrollIntoViewIfNeeded()
  await libraryLink.focus()
  const libraryScroll = await page.evaluate(() => scrollY)
  await libraryLink.press('Enter')
  await expect(page.locator('.media-detail-back')).toContainText('Back to Library')
  await capture(page, info, 'discover-navigation-back-library')
  await page.locator('.media-detail-back').press('Enter')
  await expect(page).toHaveURL(/\/library$/)
  await expect(page.locator('#library-sort-order')).toHaveValue('title')
  await expect(page.locator('.library-grid')).toHaveClass(/collection-grid--compact/)
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(libraryScroll)
  await page.goto('/lists/1')
  await expect(page.locator('.collection-card')).toHaveCount(4)
  await page.locator('.collection-card h3 a').first().click()
  await expect(page.locator('.media-detail-back')).toContainText('Back to List')
  await expect(page.locator('.media-detail-back')).toHaveAttribute('href', '/lists/1')
  await capture(page, info, 'discover-navigation-back-list')
  await page.locator('.media-detail-back').press('Enter')
  await expect(page).toHaveURL(/\/lists\/1$/)
  await expect(page.getByRole('heading', { name: 'For a rainy Sunday', exact: true })).toBeVisible()
  await page.locator('.collection-card h3 a').first().click()
  await page.reload()
  await expect(page.locator('.media-detail-back')).toContainText('Back to Discover')
  await expect(page.locator('.media-detail-back')).toHaveAttribute('href', '/discover')
  await checkLayout(page)
})
